create table if not exists transportistas (
  id bigint generated by default as identity primary key,
  nombre text not null,
  activo boolean not null default true,
  created_at timestamptz default now()
);

create table if not exists camiones (
  id bigint generated by default as identity primary key,
  transportista_id bigint references transportistas(id) on delete cascade,
  descripcion text not null,
  tipo text not null default 'km',
  precio numeric not null default 0,
  last_km numeric not null default 0,
  created_at timestamptz default now()
);
create index if not exists idx_camiones_ts on camiones(transportista_id);

create table if not exists repartos (
  id bigint generated always as identity primary key,
  fecha date,
  transportista_id bigint,
  transportista_nombre text,
  camion_id bigint,
  camion_descripcion text,
  km numeric default 0,
  precio numeric default 0,
  tipo text,
  total_flete numeric default 0,
  total_monto numeric default 0,
  inc_total numeric,
  gasto_permitido numeric default 0,
  diferencia numeric default 0,
  zona text,
  clientes jsonb default '[]'::jsonb,
  created_at timestamptz default now()
);
create index if not exists idx_repartos_fecha on repartos(fecha);

