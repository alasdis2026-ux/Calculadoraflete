-- ── RLS: acceso anon (patron del ecosistema) ──
alter table transportistas enable row level security;
alter table camiones enable row level security;
alter table repartos enable row level security;
do $$ declare t text; begin
  foreach t in array array['transportistas','camiones','repartos'] loop
    execute format('drop policy if exists anon_all on %I;', t);
    execute format('create policy anon_all on %I for all to anon using (true) with check (true);', t);
  end loop; end $$;
