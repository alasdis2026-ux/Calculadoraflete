-- Convierte `repartos` (de Flete) en la PLANILLA que consume Control de Facturas
-- y agrega las tablas de gestión (facturas / auditoría / reporte).
--
-- Cómo correrlo:  SQL Editor de Supabase (proyecto Flete) → pegar TODO → Run.
-- Es idempotente y ADITIVO: no borra ni altera los datos existentes de Flete.
